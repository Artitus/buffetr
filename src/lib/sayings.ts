const ALL_SAYINGS: readonly string[] = (
  Object.keys(SAYINGS) as VerdictWord[]
).flatMap((band) => SAYINGS[band]);

function assertSayings(lines: readonly string[]): void {
  if (lines.length !== 300) {
    throw new Error(`Buffetr sayings: expected 300, got ${lines.length}`);
  }
  const seen = new Set<string>();
  for (const line of lines) {
    const key = line.trim().toLowerCase();
    if (seen.has(key)) {
      throw new Error(`Buffetr sayings: duplicate "${line}"`);
    }
    seen.add(key);
    const periods = line.match(/\./g);
    if (!periods || periods.length !== 1 || !line.endsWith(".")) {
      throw new Error(`Buffetr sayings: one sentence only "${line}"`);
    }
  }
}

assertSayings(ALL_SAYINGS);

/** Random line for the band. Repeats the previous line only if it is the only one. */
export function pickSaying(
  band: VerdictWord | null,
  avoid?: string | null
): string {
  const pool = SAYINGS[band ?? "COOKED"];
  const size = pool.length;
  if (size === 0) return "";
  if (!avoid || size === 1) {
    return pool[Math.floor(Math.random() * size)] ?? "";
  }
  const skip = pool.indexOf(avoid);
  if (skip === -1) {
    return pool[Math.floor(Math.random() * size)] ?? "";
  }
  let index = Math.floor(Math.random() * (size - 1));
  if (index >= skip) index += 1;
  return pool[index] ?? "";
}
